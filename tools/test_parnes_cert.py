# -*- coding: utf-8 -*-
"""בדיקת סידור תעודת פרנס יום.

מאיר, שוב ושוב: "את השמות ושם האמא אותיות גדולות, את הבקשות אותיות
קטנות, מסודר בפרופורציה", ו"למה כל פעם שאני עושה פרנס לילה אני צריך
לעדכן אותך מחדש? זה ממש מטריח אותי".

הכלל אחד ופשוט: כל "שם בן/בת אם" הוא שורת שמות (גדולה), וכל מה שבא
אחריו עד השם הבא הוא בקשה (קטנה). הבדיקה הזו מריצה את המקרים שכבר
נשברו בעבר, כדי שהם לא יישברו שוב בשקט.

הרצה:  python3 tools/test_parnes_cert.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'server'))

import app  # noqa: E402

# (ההקדשה, [(תפקיד, טקסט), ...])
CASES = [
    # המקרה שמאיר שלח: ארבעה שמות, כל אחד עם בקשה משלו
    ('בנימין אייל בן הלנה שיזכה לשאיפה בלימוד התורה בשמחה ושיזכה להיות '
     'עבד השם אמיתי כל ימי חייו, אמונה רחל בת הלנה לבריאות רפואת הנפש '
     'והגוף וזיווג הגון, אלישבע ברכה בת הלנה לזיווג הגון , '
     'זיו בן נורית למנוחת הנפש',
     [('names', 'בנימין אייל בן הלנה'),
      ('req', 'שיזכה'),
      ('names', 'אמונה רחל בת הלנה'),
      ('req', 'לבריאות'),
      ('names', 'אלישבע ברכה בת הלנה'),
      ('req', 'לזיווג'),
      ('names', 'זיו בן נורית'),
      ('req', 'למנוחת')]),
    # שם שני שבא אחרי בקשה שאינה פותחת ב"שיזכה" — נבלע בעבר בתוך הבקשה
    ('טוביה טירן בן אביטל לישועות פרנסה טובה ויציאה מהחובות ולהגיע '
     'לצדיק על ראש השנה, אלישבע בת אילנה לשמחה רפואת הגוף והנפש ואמונה',
     [('names', 'טוביה טירן בן אביטל'),
      ('req', 'לישועות'),
      ('names', 'אלישבע בת אילנה'),
      ('req', 'לשמחה')]),
    # שם יחיד — הצורה הפשוטה
    ('יעקב בן שרה לרפואה שלמה',
     [('names', 'יעקב בן שרה'), ('req', 'לרפואה')]),
]


def rows(text):
    return app._cert_body([], text.split())


def main():
    bad = 0
    for ded, want in CASES:
        got = rows(ded)
        got_nr = [(r, t) for t, r in got if r in ('names', 'req')]
        ok = len(got_nr) == len(want)
        if ok:
            for (wr, wt), (gr, gt) in zip(want, got_nr):
                if gr != wr or not gt.startswith(wt.split()[0]):
                    ok = False
                    break
        # שורת שמות לעולם אינה מכילה בקשה, ושורת בקשה אינה מכילה "בן/בת"
        for r, t in got_nr:
            if r == 'req' and app._CERT_REL.search(' ' + t + ' '):
                ok = False
        print(('  ✓ ' if ok else '  ✗ ') + ded[:46] + '…')
        if not ok:
            bad += 1
            for r, t in got_nr:
                print('        %-6s %s' % (r, t))
    print('\nנכשלו: %d מתוך %d' % (bad, len(CASES)))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
